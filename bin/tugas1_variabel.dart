// Tugas 1: Variabel, Operasi Htiung, dan Komentar

void main() {
  // Deklarasi variabel
  int angka1 = 10; // Variabel angka1 bertipe integer
  int angka2 = 5;  // Variabel angka2 bertipe integer

  // Operasi hitung
  int penjumlahan = angka1 + angka2; // Penjumlahan
  int pengurangan = angka1 - angka2; // Pengurangan
  int perkalian = angka1 * angka2;   // Perkalian
  double pembagian = angka1 / angka2; // Pembagian

  // Menampilkan hasil operasi hitung
  print('Penjumlahan $angka1 + $angka2 = $penjumlahan');
  print('Pengurangan $angka1 - $angka2 = $pengurangan');
  print('Perkalian $angka1 * $angka2 = $perkalian');
  print('Pembagian $angka1 / $angka2 = $pembagian');
}